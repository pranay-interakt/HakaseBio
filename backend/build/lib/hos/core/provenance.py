"""Provenance primitives.

The integrity contract of the Hakase OS is implemented here: a scientific value
may not exist without a record of *where it came from*. Every quantity in the
system carries a :class:`Provenance`, which names one of:

``MEASURED``       an instrument/assay observation
``LITERATURE``     a value retrieved from a curated external database or paper
``COMPUTED``       the deterministic output of a cited equation
``PREDICTED``      the output of a named, versioned model (QSAR/ML)
``GUIDELINE``      a value fixed by a regulatory guideline or reference table
``USER_SUPPLIED``  a value entered by a named human
``SIMULATED``      generated by a declared, cited model for verification or
                   demonstration; never admissible as evidence
``UNAVAILABLE``    the value could not be obtained; carries the reason

There is deliberately no ``DEFAULT``, ``ASSUMED`` or ``ESTIMATED`` kind. A value
that cannot be sourced is ``UNAVAILABLE``; it is never silently filled in.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field, replace
from datetime import datetime, timezone
from enum import Enum
from typing import Any

__all__ = [
    "ApplicabilityCheck",
    "Citation",
    "Method",
    "Provenance",
    "ProvenanceKind",
    "Uncertainty",
    "utc_now",
]


def utc_now() -> datetime:
    """Timezone-aware UTC timestamp (never a naive local clock)."""
    return datetime.now(timezone.utc)


class ProvenanceKind(str, Enum):
    """How a value came to exist. See module docstring."""

    MEASURED = "measured"
    LITERATURE = "literature"
    COMPUTED = "computed"
    PREDICTED = "predicted"
    GUIDELINE = "guideline"
    USER_SUPPLIED = "user_supplied"
    SIMULATED = "simulated"
    UNAVAILABLE = "unavailable"

    @property
    def is_empirical(self) -> bool:
        """True when the value traces back to an observation of the real world."""
        return self in (ProvenanceKind.MEASURED, ProvenanceKind.LITERATURE)

    @property
    def requires_citation(self) -> bool:
        """Kinds that MUST name a primary source before they may be constructed."""
        return self in (
            ProvenanceKind.LITERATURE,
            ProvenanceKind.COMPUTED,
            ProvenanceKind.PREDICTED,
            ProvenanceKind.GUIDELINE,
            ProvenanceKind.SIMULATED,
        )

    @property
    def admissible_as_evidence(self) -> bool:
        """Whether a value of this kind may support a regulatory or GxP record.

        Simulated values exist to verify software and demonstrate workflows; they
        can never be evidence. Unavailable values are, by definition, not evidence.
        """
        return self not in (ProvenanceKind.SIMULATED, ProvenanceKind.UNAVAILABLE)


@dataclass(frozen=True, slots=True)
class Citation:
    """A primary literature or regulatory reference.

    ``key`` is a stable short identifier used in code and docstrings
    (e.g. ``"obach1999"``). ``text`` is the full human-readable reference.
    """

    key: str
    text: str
    doi: str | None = None
    url: str | None = None
    year: int | None = None

    def __post_init__(self) -> None:
        if not self.key or not self.key.strip():
            raise ValueError("Citation.key must be a non-empty identifier")
        if not self.text or not self.text.strip():
            raise ValueError(f"Citation {self.key!r} must carry full reference text")

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "text": self.text,
            "doi": self.doi,
            "url": self.url,
            "year": self.year,
        }


@dataclass(frozen=True, slots=True)
class Method:
    """A named, versioned computational method backed by citations.

    Every ``COMPUTED`` or ``PREDICTED`` quantity names the ``Method`` that produced
    it. ``assumptions`` and ``limits`` are carried with the value so a reviewer can
    see the conditions under which it is valid without reading the source.
    """

    id: str
    version: str
    name: str
    citations: tuple[Citation, ...] = ()
    assumptions: tuple[str, ...] = ()
    limits: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if not self.id:
            raise ValueError("Method.id is required")
        if not self.version:
            raise ValueError(f"Method {self.id!r} must declare a version")
        if not self.citations:
            raise ValueError(
                f"Method {self.id!r} must cite at least one primary reference. "
                "Uncited methods are not permitted (see CLAUDE.md rule 3)."
            )

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "version": self.version,
            "name": self.name,
            "citations": [c.to_dict() for c in self.citations],
            "assumptions": list(self.assumptions),
            "limits": list(self.limits),
        }


@dataclass(frozen=True, slots=True)
class Uncertainty:
    """Quantified uncertainty on a value.

    ``kind`` is one of ``"ci95"``, ``"sd"``, ``"sem"``, ``"range"``. ``lower``/``upper``
    are expressed in the same unit as the parent quantity.
    """

    kind: str
    lower: float | None = None
    upper: float | None = None
    sd: float | None = None
    n: int | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "lower": self.lower,
            "upper": self.upper,
            "sd": self.sd,
            "n": self.n,
        }


@dataclass(frozen=True, slots=True)
class ApplicabilityCheck:
    """Result of an applicability-domain check for a ``PREDICTED`` value.

    A model prediction outside the chemical/biological space the model was trained
    on is not silently returned as if trustworthy: ``in_domain`` is False and the
    reason is surfaced to the user.
    """

    in_domain: bool
    descriptor_ranges_checked: tuple[str, ...] = ()
    reason: str | None = None
    distance_metric: str | None = None
    distance_value: float | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "in_domain": self.in_domain,
            "descriptor_ranges_checked": list(self.descriptor_ranges_checked),
            "reason": self.reason,
            "distance_metric": self.distance_metric,
            "distance_value": self.distance_value,
        }


@dataclass(frozen=True, slots=True)
class Provenance:
    """The complete record of a value's origin.

    Construct via the classmethods rather than directly, so that the invariants
    for each kind are enforced.
    """

    kind: ProvenanceKind
    method: Method | None = None
    citation: Citation | None = None
    source_name: str | None = None
    source_url: str | None = None
    source_record_id: str | None = None
    retrieved_at: datetime | None = None
    actor: str | None = None
    input_ids: tuple[str, ...] = ()
    software: Mapping[str, str] = field(default_factory=dict)
    parameter_set_version: str | None = None
    applicability: ApplicabilityCheck | None = None
    reason: str | None = None
    notes: str | None = None
    recorded_at: datetime = field(default_factory=utc_now)

    def __post_init__(self) -> None:
        k = self.kind
        if k.requires_citation and self.method is None and self.citation is None:
            raise ValueError(
                f"Provenance of kind {k.value!r} requires a Method or Citation. "
                "Uncited scientific values are not permitted (CLAUDE.md rule 1)."
            )
        if k is ProvenanceKind.PREDICTED and self.applicability is None:
            raise ValueError(
                "PREDICTED values must carry an ApplicabilityCheck so that "
                "out-of-domain predictions cannot masquerade as reliable."
            )
        if k is ProvenanceKind.SIMULATED and not self.notes:
            raise ValueError(
                "SIMULATED values must record the generating parameters in notes so the "
                "simulation is reproducible and cannot be mistaken for a measurement"
            )
        if k is ProvenanceKind.UNAVAILABLE and not self.reason:
            raise ValueError("UNAVAILABLE provenance must state a reason")
        if k is ProvenanceKind.MEASURED and not (self.source_name or self.actor):
            raise ValueError("MEASURED values must name the instrument/assay or the actor")

    # -- constructors -------------------------------------------------------

    @classmethod
    def measured(
        cls,
        *,
        source_name: str,
        actor: str | None = None,
        source_record_id: str | None = None,
        notes: str | None = None,
    ) -> Provenance:
        return cls(
            kind=ProvenanceKind.MEASURED,
            source_name=source_name,
            actor=actor,
            source_record_id=source_record_id,
            notes=notes,
        )

    @classmethod
    def literature(
        cls,
        *,
        source_name: str,
        citation: Citation | None = None,
        source_url: str | None = None,
        source_record_id: str | None = None,
        retrieved_at: datetime | None = None,
        notes: str | None = None,
    ) -> Provenance:
        if citation is None:
            citation = Citation(
                key=f"db:{source_name}",
                text=f"Retrieved from {source_name}",
                url=source_url,
            )
        return cls(
            kind=ProvenanceKind.LITERATURE,
            citation=citation,
            source_name=source_name,
            source_url=source_url,
            source_record_id=source_record_id,
            retrieved_at=retrieved_at or utc_now(),
            notes=notes,
        )

    @classmethod
    def computed(
        cls,
        *,
        method: Method,
        input_ids: Sequence[str] = (),
        software: Mapping[str, str] | None = None,
        parameter_set_version: str | None = None,
        notes: str | None = None,
    ) -> Provenance:
        return cls(
            kind=ProvenanceKind.COMPUTED,
            method=method,
            input_ids=tuple(input_ids),
            software=dict(software or {}),
            parameter_set_version=parameter_set_version,
            notes=notes,
        )

    @classmethod
    def predicted(
        cls,
        *,
        method: Method,
        applicability: ApplicabilityCheck,
        input_ids: Sequence[str] = (),
        software: Mapping[str, str] | None = None,
        notes: str | None = None,
    ) -> Provenance:
        return cls(
            kind=ProvenanceKind.PREDICTED,
            method=method,
            applicability=applicability,
            input_ids=tuple(input_ids),
            software=dict(software or {}),
            notes=notes,
        )

    @classmethod
    def guideline(
        cls,
        *,
        citation: Citation,
        source_record_id: str | None = None,
        parameter_set_version: str | None = None,
        notes: str | None = None,
    ) -> Provenance:
        return cls(
            kind=ProvenanceKind.GUIDELINE,
            citation=citation,
            source_record_id=source_record_id,
            parameter_set_version=parameter_set_version,
            notes=notes,
        )

    @classmethod
    def simulated(
        cls,
        *,
        method: Method,
        parameters: str,
        seed: int | None = None,
        software: Mapping[str, str] | None = None,
    ) -> Provenance:
        note = f"SIMULATED - not a measurement. generator parameters: {parameters}"
        if seed is not None:
            note += f"; seed={seed}"
        return cls(
            kind=ProvenanceKind.SIMULATED,
            method=method,
            software=dict(software or {}),
            source_name="simulation",
            notes=note,
        )

    @classmethod
    def user_supplied(cls, *, actor: str, notes: str | None = None) -> Provenance:
        return cls(kind=ProvenanceKind.USER_SUPPLIED, actor=actor, notes=notes)

    @classmethod
    def unavailable(cls, *, reason: str, source_name: str | None = None) -> Provenance:
        return cls(kind=ProvenanceKind.UNAVAILABLE, reason=reason, source_name=source_name)

    # -- helpers ------------------------------------------------------------

    def with_note(self, note: str) -> Provenance:
        merged = f"{self.notes}; {note}" if self.notes else note
        return replace(self, notes=merged)

    @property
    def citations(self) -> tuple[Citation, ...]:
        """All citations backing this value (method citations plus direct citation)."""
        out: list[Citation] = []
        if self.method is not None:
            out.extend(self.method.citations)
        if self.citation is not None:
            out.append(self.citation)
        seen: set[str] = set()
        unique: list[Citation] = []
        for c in out:
            if c.key not in seen:
                seen.add(c.key)
                unique.append(c)
        return tuple(unique)

    def to_dict(self) -> dict[str, Any]:
        return {
            "kind": self.kind.value,
            "method": self.method.to_dict() if self.method else None,
            "citation": self.citation.to_dict() if self.citation else None,
            "citations": [c.to_dict() for c in self.citations],
            "source_name": self.source_name,
            "source_url": self.source_url,
            "source_record_id": self.source_record_id,
            "retrieved_at": self.retrieved_at.isoformat() if self.retrieved_at else None,
            "actor": self.actor,
            "input_ids": list(self.input_ids),
            "software": dict(self.software),
            "parameter_set_version": self.parameter_set_version,
            "applicability": self.applicability.to_dict() if self.applicability else None,
            "reason": self.reason,
            "notes": self.notes,
            "recorded_at": self.recorded_at.isoformat(),
        }

    def fingerprint(self) -> str:
        """Stable hash of the provenance-defining fields (excludes recorded_at)."""
        payload = {
            "kind": self.kind.value,
            "method": f"{self.method.id}@{self.method.version}" if self.method else None,
            "citation": self.citation.key if self.citation else None,
            "source": self.source_name,
            "record": self.source_record_id,
            "inputs": list(self.input_ids),
            "params": self.parameter_set_version,
            "software": dict(sorted(self.software.items())),
        }
        blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(blob.encode()).hexdigest()[:16]
