"""Create the dev/demo principals on a running API (development only).

    python scripts/seed_dev.py [http://127.0.0.1:8000]

Account definitions come from ``dev_principals.example.json``, which contains no
passwords. On first run a random password is generated for each account with
:func:`secrets.token_urlsafe`, saved to ``dev_principals.local.json`` (gitignored,
owner-readable only) and printed once. Later runs reuse the saved passwords, so
the administrator can still log in to seed accounts added afterwards.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
from pathlib import Path

import httpx

HERE = Path(__file__).parent
EXAMPLE = HERE / "dev_principals.example.json"
LOCAL = HERE / "dev_principals.local.json"


def _load_passwords() -> dict[str, str]:
    if LOCAL.exists():
        return json.loads(LOCAL.read_text())["passwords"]
    return {}


def _save_passwords(passwords: dict[str, str]) -> None:
    LOCAL.write_text(json.dumps({
        "_note": "Generated by seed_dev.py. Local development credentials; never commit.",
        "passwords": passwords,
    }, indent=2) + "\n")
    os.chmod(LOCAL, 0o600)


def main() -> None:
    base = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000") + "/api"
    accounts = json.loads(EXAMPLE.read_text())["principals"]

    passwords = _load_passwords()
    new_ids = [a["principal_id"] for a in accounts if a["principal_id"] not in passwords]
    for pid in new_ids:
        passwords[pid] = "dev-" + secrets.token_urlsafe(18)
    if new_ids:
        _save_passwords(passwords)

    admin = accounts[0]
    c = httpx.Client(timeout=30)
    if not c.get(f"{base}/setup").json()["initialised"]:
        token = os.environ.get("HOS_BOOTSTRAP_TOKEN") or (sys.argv[2] if len(sys.argv) > 2
                                                          else "")
        if not token:
            sys.exit("first run: pass the setup token printed in the server log as the second "
                     "argument, or set HOS_BOOTSTRAP_TOKEN for both the server and this script")
        c.post(f"{base}/setup", json={
            "principal_id": admin["principal_id"], "name": admin["name"],
            "password": passwords[admin["principal_id"]], "setup_token": token,
        }).raise_for_status()
    login = c.post(f"{base}/auth/login", json={
        "principal_id": admin["principal_id"], "password": passwords[admin["principal_id"]],
    })
    if login.status_code != 200:
        sys.exit(
            f"administrator login failed ({login.status_code}). If this instance was set up "
            f"before {LOCAL.name} existed, use that instance's admin password or a fresh "
            "HOS_DATA_DIR."
        )
    h = {"Authorization": f"Bearer {login.json()['token']}"}

    existing = {p["id"] for p in c.get(f"{base}/principals", headers=h).json()}
    created = []
    for a in accounts[1:]:
        if a["principal_id"] not in existing:
            c.post(f"{base}/principals", headers=h,
                   json={**a, "password": passwords[a["principal_id"]]}).raise_for_status()
            created.append(a["principal_id"])

    print("principals:", sorted(existing | {a["principal_id"] for a in accounts}))
    if new_ids:
        print(f"\nGenerated credentials (also saved to {LOCAL}, mode 600):")
        for pid in new_ids:
            print(f"  {pid:6s} {passwords[pid]}")
    else:
        print(f"credentials: see {LOCAL}")


if __name__ == "__main__":
    main()
