@dataclass(frozen=True, slots=True)
class InstructionPackage:
    """Everything an executing laboratory needs. ``to_bundle()`` renders the dispatch zip."""

    study_reference: str
    protocol: ProtocolDocument
    data_template: DataTemplate
    sample_manifest: tuple[Mapping[str, Any], ...]
    return_instructions: str
    expert_determinations: tuple[ExpertDetermination, ...] = ()

    def files(self) -> dict[str, bytes]:
        manifest_csv = io.StringIO()
        if self.sample_manifest:
            keys = list(self.sample_manifest[0].keys())
            w = csv.DictWriter(manifest_csv, fieldnames=keys, lineterminator="\n")
            w.writeheader()
            for row in self.sample_manifest:
                w.writerow(dict(row))
        return {
            "protocol.md": self.protocol.to_markdown().encode(),
            "protocol.json": json.dumps(self.protocol.to_dict(), indent=2, sort_keys=True).encode(),
            "data_template.csv": self.data_template.blank_csv(self.study_reference).encode(),
            "data_template.json": json.dumps(self.data_template.to_dict(), indent=2).encode(),
            "sample_manifest.csv": manifest_csv.getvalue().encode(),
            "RETURN_INSTRUCTIONS.md": self.return_instructions.encode(),
        }

    def to_bundle(self) -> bytes:
        """A deterministic zip (fixed timestamps) with a SHA-256 manifest of its contents."""
        files = self.files()
        manifest = {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())}
        files["MANIFEST.json"] = json.dumps(
            {"study_reference": self.study_reference, "protocol_hash": self.protocol.content_hash,
             "files": manifest}, indent=2, sort_keys=True).encode()
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            for name in sorted(files):
                info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, files[name])
        return buf.getvalue()

    def to_dict(self) -> dict[str, Any]:
        return {
            "study_reference": self.study_reference,
            "protocol": self.protocol.to_dict(),
            "data_template": self.data_template.to_dict(),
            "sample_manifest": [dict(r) for r in self.sample_manifest],
            "return_instructions": self.return_instructions,
            "expert_determinations": [e.to_dict() for e in self.expert_determinations],
        }


