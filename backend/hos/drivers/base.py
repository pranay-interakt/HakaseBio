"""The StudyDriver interface: the contract between the kernel and a study type.

The design follows the shape of an operating-system driver model. The base class is
the *subsystem*: it owns everything that must be identical for every study type and
cannot be skipped by a driver - strict parsing of returned data, SHA-256 of the raw
file, unit conversion, detection of simulated data, propagation of the simulation
taint, the requirement that every interpretive statement is cited, and the
simulated-data disclaimer on reports. A concrete driver only supplies the
study-specific hooks.

Lifecycle of a study through its driver::

    probe(requirement)        -> Support            does this driver serve the requirement?
    design()                  -> ProtocolDocument   (DESIGNED)
    plan()                    -> StudyPlan          (PLANNED; never a cost - cost is a lab quote)
    data_template()           -> DataTemplate       the exact CSV the lab must return
    instruction_package()     -> InstructionPackage (DISPATCHED; rendered as a dispatch bundle)
    ingest(raw bytes)         -> IngestedData       (DATA_RECEIVED; strict, hashed)
    analyze()                 -> AnalysisResult     (ANALYZED; cited methods, Quantities)
    interpret()               -> Interpretation     cited rule-based statements only
    report()                  -> StudyReport        (REPORTED)
    simulate()                -> SimulatedDataset   optional; SIMULATED, seeded, parameters recorded

Anything requiring expert judgement (e.g. a NOAEL) is declared by the driver as an
:class:`ExpertDetermination` and recorded by the kernel only with a human signature.
"""

