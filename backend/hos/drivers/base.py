@dataclass(frozen=True, slots=True)
class StudyReport:
    title: str
    ctd_section: str
    sections: tuple[ReportSection, ...]
    evidence_admissible: bool
    disclaimer: str | None = None

    def to_dict(self) -> dict[str, Any]:
        d = {"title": self.title, "ctd_section": self.ctd_section,
             "sections": [s.to_dict() for s in self.sections],
             "evidence_admissible": self.evidence_admissible, "disclaimer": self.disclaimer}
        d["content_hash"] = canonical_hash(d)
        return d

    @property
    def content_hash(self) -> str:
        return str(self.to_dict()["content_hash"])

    def to_markdown(self) -> str:
        out = [f"# {self.title}", "", f"*CTD section:* {self.ctd_section}  ",
               f"*Report hash:* `{self.content_hash}`", ""]
        if self.disclaimer:
            out += [f"> **{self.disclaimer}**", ""]
        for s in self.sections:
            out += [f"## {s.heading}", "", s.body, ""]
            for t in s.tables:
                out += [f"**{t.title}**", "", "| " + " | ".join(t.columns) + " |",
                        "|" + "---|" * len(t.columns)]
                for r in t.rows:
                    out.append("| " + " | ".join(_cell_md(c) for c in r) + " |")
                if t.note:
                    out += ["", f"*{t.note}*"]
                out.append("")
        return "\n".join(out) + "\n"


def _cell_md(c: Cell) -> str:
    if isinstance(c, Quantity):
        if not c.is_available:
            return f"unavailable ({c.provenance.reason})"
        unc = ""
        u = c.uncertainty
        if u is not None and getattr(u, "kind", None) == "ci95" and u.lower is not None:
            unc = f" (95% CI {u.lower:.3g}-{u.upper:.3g})"
        unit = "" if c.unit == "dimensionless" else f" {c.unit}"
        flags = f" [{', '.join(c.qc_flags)}]" if c.qc_flags else ""
        return f"{c.value:.4g}{unit}{unc} _{c.kind.value}_{flags}"
    return "" if c is None else str(c)


