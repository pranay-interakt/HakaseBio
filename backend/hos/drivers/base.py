Cell = Quantity | str | int | None


@dataclass(frozen=True, slots=True)
class Table:
    """A result table. Numeric cells must be :class:`Quantity` (no bare floats); ``int`` is
    allowed only for counts."""

    title: str
    columns: tuple[str, ...]
    rows: tuple[tuple[Cell, ...], ...]
    note: str | None = None

    def __post_init__(self) -> None:
        for r in self.rows:
            if len(r) != len(self.columns):
                raise DriverError(f"table {self.title!r}: row width {len(r)} != {len(self.columns)}")
            for c in r:
                if isinstance(c, (bool, float)):
                    raise DriverError(
                        f"table {self.title!r} contains a bare float {c!r}; numeric results must "
                        "be Quantity objects carrying provenance")

    def map_quantities(self, fn: Any) -> Table:
        return replace(self, rows=tuple(tuple(fn(c) if isinstance(c, Quantity) else c for c in r)
                                        for r in self.rows))

    def quantities(self) -> list[Quantity]:
        return [c for r in self.rows for c in r if isinstance(c, Quantity)]

    def to_dict(self) -> dict[str, Any]:
        return {"title": self.title, "columns": list(self.columns),
                "rows": [[c.to_dict() if isinstance(c, Quantity) else c for c in r]
                         for r in self.rows],
                "note": self.note}


@dataclass(frozen=True, slots=True)
class AnalysisResult:
    """Provenance-typed output of a driver's analysis."""

    quantities: Mapping[str, Quantity]
    tables: tuple[Table, ...]
    qc: QCVerdict
    evidence_admissible: bool
    series: tuple[Mapping[str, Any], ...] = ()
    notes: tuple[str, ...] = ()

    def all_quantities(self) -> list[Quantity]:
        out = list(self.quantities.values())
        for t in self.tables:
            out.extend(t.quantities())
        return out

    def to_dict(self) -> dict[str, Any]:
        return {
            "quantities": {k: q.to_dict() for k, q in self.quantities.items()},
            "tables": [t.to_dict() for t in self.tables],
            "qc": self.qc.to_dict(),
            "evidence_admissible": self.evidence_admissible,
            "series": [dict(s) for s in self.series],
            "notes": list(self.notes),
        }


