@dataclass(frozen=True, slots=True)
class DataTemplate:
    """The exact form in which results must be returned: a UTF-8 CSV with ``# key: value``
    metadata lines, one header row and data rows."""

    template_id: str
    columns: tuple[DataColumn, ...]
    description: str
    metadata: tuple[MetadataField, ...] = STANDARD_METADATA
    allow_extra_columns: bool = False

    def __post_init__(self) -> None:
        names = [c.name for c in self.columns]
        if len(set(names)) != len(names):
            raise DriverError(f"template {self.template_id}: duplicate column names")

    def column(self, name: str) -> DataColumn:
        for c in self.columns:
            if c.name == name:
                return c
        raise KeyError(name)

    def header(self) -> list[str]:
        return [f"{c.name} [{c.unit}]" if c.unit else c.name for c in self.columns]

    def blank_csv(self, study_reference: str = "") -> str:
        buf = io.StringIO()
        buf.write(f"# hos-template: {self.template_id}\n")
        for m in self.metadata:
            val = study_reference if m.key == "study_reference" else ""
            buf.write(f"# {m.key}: {val}\n")
        csv.writer(buf, lineterminator="\n").writerow(self.header())
        return buf.getvalue()

    def to_dict(self) -> dict[str, Any]:
        return {"template_id": self.template_id, "description": self.description,
                "columns": [c.to_dict() for c in self.columns],
                "metadata": [m.to_dict() for m in self.metadata],
                "csv_header": self.header(), "allow_extra_columns": self.allow_extra_columns}


@dataclass(frozen=True, slots=True)
class IngestedData:
    """Validated, typed, unit-normalised data parsed from a returned file."""

    template_id: str
    records: tuple[Mapping[str, Any], ...]
    metadata: Mapping[str, str]
    origin: DataOrigin
    file_sha256: str
    filename: str
    conversions: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()

    @property
    def is_simulated(self) -> bool:
        return self.origin is DataOrigin.SIMULATED

    def provenance(self, *, record_id: str | None = None) -> Provenance:
        """Provenance for raw observations taken from this file."""
        rid = record_id or f"sha256:{self.file_sha256}"
        if self.is_simulated:
            method_id = self.metadata.get("hos-simulation-method", "")
            try:
                m = get_method(method_id)
            except KeyError as exc:
                raise DriverError(f"simulated file names unknown generator {method_id!r}") from exc
            seed = self.metadata.get("hos-simulation-seed")
            return Provenance.simulated(
                method=m,
                parameters=self.metadata.get("hos-simulation-parameters", "unrecorded"),
                seed=int(seed) if seed and seed.lstrip("-").isdigit() else None,
            )
        source = self.metadata.get("instrument") or self.metadata.get("laboratory", "laboratory")
        return Provenance.measured(
            source_name=f"{self.metadata.get('laboratory', '')}: {source}".strip(": "),
            actor=self.metadata.get("analyst"),
            source_record_id=rid,
            notes=f"run_date={self.metadata.get('run_date')}; file={self.filename}",
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "template_id": self.template_id,
            "records": [dict(r) for r in self.records],
            "n_records": len(self.records),
            "metadata": dict(self.metadata),
            "origin": self.origin.value,
            "file_sha256": self.file_sha256,
            "filename": self.filename,
            "conversions": list(self.conversions),
            "warnings": list(self.warnings),
        }

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> IngestedData:
        return cls(
            template_id=d["template_id"], records=tuple(d["records"]), metadata=d["metadata"],
            origin=DataOrigin(d["origin"]), file_sha256=d["file_sha256"], filename=d["filename"],
            conversions=tuple(d.get("conversions", ())), warnings=tuple(d.get("warnings", ())),
        )


def _parse_header_cell(cell: str) -> tuple[str, str | None]:
    cell = cell.strip()
    if cell.endswith("]") and "[" in cell:
        name, _, unit = cell[:-1].partition("[")
        return name.strip(), unit.strip()
    return cell, None


def parse_return_file(content: bytes, template: DataTemplate, *, filename: str = "upload.csv",
                      claimed_origin: DataOrigin = DataOrigin.MEASURED) -> IngestedData:
    """Strictly validate a returned CSV against ``template``.

    Collects every error (with line numbers) and raises :class:`IngestError` if any.
    The SHA-256 of the exact bytes received is recorded. A file carrying the simulation
    marker is SIMULATED regardless of what the uploader claims; a claim of SIMULATED is
    always honoured (data can be downgraded, never laundered upward).
    """
    sha = hashlib.sha256(content).hexdigest()
    errors: list[str] = []
    try:
        text = content.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise IngestError([f"file is not valid UTF-8: {exc}"]) from exc
    if not text.strip():
        raise IngestError(["file is empty"])

    lines = text.splitlines()
    metadata: dict[str, str] = {}
    i = 0
    while i < len(lines) and (lines[i].startswith("#") or not lines[i].strip()):
        line = lines[i].lstrip("#").strip()
        if line:
            key, sep, value = line.partition(":")
            if not sep:
                errors.append(f"line {i + 1}: metadata must be '# key: value'")
            else:
                k = key.strip()
                if k in metadata:
                    errors.append(f"line {i + 1}: duplicate metadata key {k!r}")
                metadata[k] = value.strip()
        i += 1
    header_line_no = i + 1

    tid = metadata.get("hos-template")
    if tid is not None and tid != template.template_id:
        errors.append(f"file declares template {tid!r} but this study expects "
                      f"{template.template_id!r}")
    for m in template.metadata:
        if m.required and not metadata.get(m.key):
            errors.append(f"missing required metadata '# {m.key}: ...' ({m.description})")
    run_date = metadata.get("run_date")
    if run_date:
        from datetime import date
        try:
            date.fromisoformat(run_date)
        except ValueError:
            errors.append(f"metadata run_date {run_date!r} is not an ISO 8601 date (YYYY-MM-DD)")

    if i >= len(lines):
        raise IngestError(errors + ["no header row found"])

    reader = csv.reader(lines[i:])
    try:
        raw_header = next(reader)
    except StopIteration:
        raise IngestError(errors + ["no header row found"]) from None
    parsed_header = [_parse_header_cell(h) for h in raw_header]
    names = [n for n, _ in parsed_header]
    seen: set[str] = set()
    for n in names:
        if n in seen:
            errors.append(f"line {header_line_no}: duplicate column {n!r}")
        seen.add(n)
    known = {c.name for c in template.columns}
    for c in template.columns:
        if c.required and c.name not in names:
            errors.append(f"line {header_line_no}: missing required column {c.name!r}")
    unknown = [n for n in names if n not in known]
    if unknown and not template.allow_extra_columns:
        errors.append(f"line {header_line_no}: unexpected column(s) {unknown}; "
                      f"expected {template.header()}")

    conversions: list[str] = []
    col_units: dict[str, str | None] = {}
    for n, unit in parsed_header:
        if n not in known:
            continue
        col = template.column(n)
        if unit is None:
            col_units[n] = col.unit
            continue
        if col.kind != "number" or col.unit_column:
            errors.append(f"line {header_line_no}: column {n!r} takes no unit in the header")
            continue
        if not U.is_valid_unit(unit):
            errors.append(f"line {header_line_no}: column {n!r} has unrecognised unit {unit!r}")
            continue
        assert col.unit is not None
        if not U.compatible(unit, col.unit):
            errors.append(f"line {header_line_no}: column {n!r} unit {unit!r} is not "
                          f"dimensionally compatible with {col.unit!r}")
            continue
        col_units[n] = unit
        if U.parse_unit(unit) != U.parse_unit(col.unit):
            conversions.append(f"{n}: {unit} -> {col.unit}")

    records: list[dict[str, Any]] = []
    for row_idx, row in enumerate(reader):
        line_no = header_line_no + 1 + row_idx
        if not row or all(not c.strip() for c in row):
            continue
        if len(row) != len(names):
            errors.append(f"line {line_no}: expected {len(names)} fields, found {len(row)}")
            continue
        rec: dict[str, Any] = {}
        for (n, _), cell in zip(parsed_header, row, strict=True):
            if n not in known:
                continue
            col = template.column(n)
            cell = cell.strip()
            if cell == "":
                if col.required:
                    errors.append(f"line {line_no}: column {n!r} is required but empty")
                rec[n] = None
                continue
            if col.kind == "text":
                if col.choices and cell not in col.choices:
                    errors.append(f"line {line_no}: {n!r} value {cell!r} not one of "
                                  f"{list(col.choices)}")
                rec[n] = cell
                continue
            if col.kind == "integer":
                try:
                    iv = int(cell)
                except ValueError:
                    errors.append(f"line {line_no}: {n!r} value {cell!r} is not an integer")
                    continue
                v: float = float(iv)
            else:
                try:
                    v = float(cell)
                except ValueError:
                    errors.append(f"line {line_no}: {n!r} value {cell!r} is not a number")
                    continue
                if not math.isfinite(v):
                    errors.append(f"line {line_no}: {n!r} value {cell!r} is not finite")
                    continue
                if col.unit is not None:
                    src_unit = col_units.get(n) or col.unit
                    if U.parse_unit(src_unit) != U.parse_unit(col.unit):
                        v = U.convert(v, src_unit, col.unit)
            if col.minimum is not None and (v < col.minimum or (col.exclusive_minimum and v == col.minimum)):
                errors.append(f"line {line_no}: {n!r} value {v:g} below physical minimum "
                              f"{'>' if col.exclusive_minimum else '>='} {col.minimum:g}")
            if col.maximum is not None and v > col.maximum:
                errors.append(f"line {line_no}: {n!r} value {v:g} above physical maximum "
                              f"{col.maximum:g}")
            rec[n] = int(v) if col.kind == "integer" else v
        for col in template.columns:
            if col.unit_column and rec.get(col.name) is not None:
                u = rec.get(col.unit_column)
                if not u or not U.is_valid_unit(str(u)):
                    errors.append(f"line {line_no}: {col.unit_column!r} value {u!r} is not a "
                                  f"recognised unit for {col.name!r}")
        records.append(rec)

    if not records and not errors:
        errors.append("file contains a header but no data rows")
    if errors:
        raise IngestError(errors)

    marked = (metadata.get(SIMULATION_MARKER, "").lower() in ("true", "yes", "1")
              or metadata.get("instrument", "").lower().startswith("simulation:"))
    origin = DataOrigin.SIMULATED if (marked or claimed_origin is DataOrigin.SIMULATED) \
        else DataOrigin.MEASURED
    if origin is DataOrigin.SIMULATED and not metadata.get("hos-simulation-method"):
        raise IngestError(["simulated data must declare '# hos-simulation-method: <method id>'"])
    return IngestedData(
        template_id=template.template_id, records=tuple(records), metadata=metadata,
        origin=origin, file_sha256=sha, filename=filename, conversions=tuple(conversions),
    )


