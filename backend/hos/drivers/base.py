@dataclass(frozen=True, slots=True)
class ProtocolDocument:
    """A structured, versionable protocol. ``content_hash`` is what a signature binds to."""

    driver_id: str
    driver_version: str
    title: str
    objective: str
    hypothesis: str | None
    test_article: Mapping[str, Any]
    test_system: Mapping[str, Any]
    design: Mapping[str, Any]
    steps: tuple[ProtocolStep, ...]
    acceptance_criteria: tuple[AcceptanceCriterion, ...]
    materials: tuple[str, ...]
    deliverables: tuple[str, ...]
    glp: bool
    references: tuple[Citation, ...]
    regulatory_basis: tuple[str, ...] = ()
    parameters: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.references:
            raise DriverError(f"protocol {self.title!r} must cite at least one reference")
        if not self.steps:
            raise DriverError(f"protocol {self.title!r} has no steps")

    def to_dict(self) -> dict[str, Any]:
        d = {
            "driver_id": self.driver_id,
            "driver_version": self.driver_version,
            "title": self.title,
            "objective": self.objective,
            "hypothesis": self.hypothesis,
            "test_article": dict(self.test_article),
            "test_system": dict(self.test_system),
            "design": dict(self.design),
            "steps": [s.to_dict() for s in self.steps],
            "acceptance_criteria": [a.to_dict() for a in self.acceptance_criteria],
            "materials": list(self.materials),
            "deliverables": list(self.deliverables),
            "glp": self.glp,
            "references": [c.to_dict() for c in self.references],
            "regulatory_basis": list(self.regulatory_basis),
            "parameters": dict(self.parameters),
        }
        d["content_hash"] = canonical_hash(d)
        return d

    @property
    def content_hash(self) -> str:
        return str(self.to_dict()["content_hash"])

    def to_markdown(self) -> str:
        out = [f"# {self.title}", "",
               f"*Driver:* `{self.driver_id}` v{self.driver_version}  ",
               f"*GLP:* {'yes (21 CFR Part 58)' if self.glp else 'no'}  ",
               f"*Protocol hash:* `{self.content_hash}`", "",
               "## Objective", self.objective, ""]
        if self.hypothesis:
            out += ["## Hypothesis", self.hypothesis, ""]
        out += ["## Test article"] + [f"- **{k}:** {v}" for k, v in self.test_article.items()] + [""]
        out += ["## Test system"] + [f"- **{k}:** {v}" for k, v in self.test_system.items()] + [""]
        out += ["## Design"] + [f"- **{k}:** {_fmt(v)}" for k, v in self.design.items()] + [""]
        out += ["## Procedure"]
        for s in self.steps:
            out.append(f"{s.number}. **{s.title}.** {s.instruction}")
            for cp in s.critical_parameters:
                out.append(f"   - critical: {cp}")
        out += ["", "## Acceptance criteria"]
        out += [f"- `{a.code}`: {a.description} *(basis: {a.basis})*" for a in self.acceptance_criteria]
        out += ["", "## Materials"] + [f"- {m}" for m in self.materials]
        out += ["", "## Deliverables"] + [f"- {d}" for d in self.deliverables]
        if self.regulatory_basis:
            out += ["", "## Regulatory basis"] + [f"- {r}" for r in self.regulatory_basis]
        out += ["", "## References"] + [f"- [{c.key}] {c.text}" + (f" doi:{c.doi}" if c.doi else "")
                                        for c in self.references]
        return "\n".join(out) + "\n"


def _fmt(v: Any) -> str:
    if isinstance(v, (list, tuple)):
        return ", ".join(_fmt(x) for x in v)
    if isinstance(v, dict):
        return "; ".join(f"{k}: {_fmt(x)}" for k, x in v.items())
    return str(v)


