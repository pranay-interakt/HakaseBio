"""
HakaseAI Evidence Object — shared primitives.

This module operationalizes the Evidence Framework Specification (doc 04) and
the recurring envelope shape described in each Scientific Service
Specification's Section 14 ("Evidence Generated by the Service"), docs 07-11.

=====================================================================
ASSUMPTIONS MADE WHILE FORMALIZING — FLAG FOR SCIENTIFIC/ENGINEERING REVIEW
=====================================================================
The source specifications describe these structures in prose/diagram form
only. Turning them into a concrete schema required a few judgment calls that
were NOT specified in the documents and should be confirmed by the platform
team before this is treated as final:

1. Per-field confidence (the "{ value, confidence }" pattern attached to
   individual descriptors, e.g. molecular_weight.confidence) is modeled here
   as a lightweight `FieldConfidence` (tier + optional numeric score +
   optional rationale). The specs never define whether this is meant to be
   as rich as the platform-wide Confidence contract in Evidence Framework §7
   -- a deliberately smaller model was chosen here.

2. Evidence Framework §4 lists "confidence" and "uncertainty" as flat,
   top-level mandatory fields on every Evidence Object. Each service's
   Section 14 schematic instead surfaces a domain-specific
   `confidence_summary` block (e.g. deterministic_tier / embedding_tier).
   This module treats `confidence_summary` as the service's concrete
   instantiation of the platform-wide `confidence` field, and adds a
   separate top-level `uncertainty` block per Evidence Framework §8. This
   mapping is an interpretation, not a decision made in the source docs.

3. Numeric confidence scores are constrained to [0, 1] per Evidence
   Framework §7, but no document defines how qualitative tiers (e.g.
   "exact", "reduced", "unavailable") map onto that numeric scale.
   `CONFIDENCE_TIER_DEFAULTS` below is a placeholder mapping, not a
   scientifically calibrated one -- it exists only so a numeric value is
   always derivable when needed (e.g. by the Decision Engine).

4. Evidence Framework §8 states "U_output = f(U_inputs, U_model)" but never
   defines f(). `UncertaintyBlock.output_uncertainty` is left as a plain
   optional float; the combination function must be defined by whoever
   implements the Decision Engine (see Decision & Reasoning Framework, doc 05).

5. Large scientific assets (embeddings, coordinate files) are represented
   here as object-storage references (`storage_uri`), consistent with
   Evidence Framework §12 ("coordinate files by reference") and the
   Database Design Specification (doc 13, §6-7), rather than being inlined
   as raw arrays.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from enum import Enum
from typing import Any, ClassVar, Generic, TypeVar

from pydantic import BaseModel, ConfigDict, Field, field_validator

T = TypeVar("T")


def _utcnow() -> datetime:
    return datetime.now(UTC)


# ---------------------------------------------------------------------------
# Confidence & Validation primitives  (Evidence Framework §7, §9, §10)
# ---------------------------------------------------------------------------


class ConfidenceTier(str, Enum):
    """Qualitative confidence tier attached to an individual computed field."""

    EXACT = "exact"  # deterministic, closed-form computation
    HIGH = "high"
    MODERATE = "moderate"
    LOW = "low"
    REDUCED = "reduced"  # computed, but with known/flagged degradation
    UNAVAILABLE = "unavailable"  # could not be computed for this input


# See ASSUMPTION 3 above -- placeholder only, not scientifically calibrated.
CONFIDENCE_TIER_DEFAULTS: dict[ConfidenceTier, float | None] = {
    ConfidenceTier.EXACT: 1.0,
    ConfidenceTier.HIGH: 0.85,
    ConfidenceTier.MODERATE: 0.6,
    ConfidenceTier.LOW: 0.35,
    ConfidenceTier.REDUCED: 0.5,
    ConfidenceTier.UNAVAILABLE: None,
}


class FieldConfidence(BaseModel):
    """Per-field confidence, attached to individual descriptors/predictions."""

    model_config = ConfigDict(extra="forbid")

    tier: ConfidenceTier
    numerical_confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Optional explicit [0,1] score. If unset, consumers may "
        "fall back to CONFIDENCE_TIER_DEFAULTS[tier] -- see ASSUMPTION 3.",
    )
    rationale: str | None = Field(
        default=None, description="Short human-readable justification for this tier."
    )


class ValueConfidence(BaseModel, Generic[T]):
    """Generic '{ value, confidence }' leaf node -- the recurring pattern in
    every service spec's Section 14 schematic (e.g. molecular_weight,
    gravy_score, aliphatic_index)."""

    model_config = ConfigDict(extra="forbid")

    value: T | None
    confidence: FieldConfidence


class ValidationStatus(str, Enum):
    """Evidence Framework §10 -- mandatory validation_status enum."""

    NOT_VALIDATED = "not_validated"
    INTERNALLY_VALIDATED = "internally_validated"
    CROSS_SERVICE_CONSISTENT = "cross_service_consistent"
    EXPERIMENTALLY_SUPPORTED = "experimentally_supported"
    DEPRECATED = "deprecated"


class ExecutionState(str, Enum):
    """Scientific Workflow Specification §13 -- task execution states.
    Not part of the Evidence Object itself, but referenced by Job/audit
    records that reference this evidence."""

    SUCCESS = "success"
    PARTIAL_SUCCESS = "partial_success"
    FAILED = "failed"
    SKIPPED = "skipped"


# ---------------------------------------------------------------------------
# Uncertainty  (Evidence Framework §8)
# ---------------------------------------------------------------------------


class UncertaintyBlock(BaseModel):
    """U_output = f(U_inputs, U_model). Components are kept separate rather
    than collapsed into one score, per Evidence Framework §8 ('inherited
    uncertainty must remain visible instead of collapsing into a single
    score')."""

    model_config = ConfigDict(extra="forbid")

    inherited_uncertainty: float | None = Field(default=None, ge=0.0, le=1.0)
    model_uncertainty: float | None = Field(default=None, ge=0.0, le=1.0)
    numerical_uncertainty: float | None = Field(default=None, ge=0.0, le=1.0)
    output_uncertainty: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Combined uncertainty. NOTE: the combination function f() "
        "is not defined in Evidence Framework §8 -- see module docstring "
        "ASSUMPTION 4.",
    )
    sources: list[str] = Field(
        default_factory=list,
        description="e.g. ['measurement_uncertainty', 'model_uncertainty', "
        "'missing_information', 'ensemble_variance'] per Evidence Framework §8.",
    )


# ---------------------------------------------------------------------------
# Applicability Domain  (Evidence Framework §9)
# ---------------------------------------------------------------------------


class ApplicabilityDomain(BaseModel):
    model_config = ConfigDict(extra="forbid")

    supported_peptide_length: tuple[int, int] | None = None
    residue_types_supported: list[str] = Field(default_factory=list)
    modification_support: list[str] = Field(default_factory=list)
    modality_support: list[str] = Field(default_factory=list)
    similarity_to_training_distribution: float | None = Field(default=None, ge=0.0, le=1.0)
    extrapolation_flag: bool = Field(
        default=False,
        description="True if this input lies outside the validated domain. "
        "Per Evidence Framework §9, out-of-domain predictions are RETAINED, "
        "never dropped -- only flagged.",
    )


# ---------------------------------------------------------------------------
# Metadata  (Evidence Framework §5)
# ---------------------------------------------------------------------------


class MetadataBlock(BaseModel):
    model_config = ConfigDict(extra="forbid")

    platform_version: str
    service_version: str
    model_versions: dict[str, str] = Field(
        default_factory=dict, description="model_name -> version/checkpoint id"
    )
    software_versions: dict[str, str] = Field(default_factory=dict)
    configuration_hash: str
    execution_environment: str
    runtime_seconds: float | None = None
    hardware: str | None = None
    input_identifiers: list[str] = Field(default_factory=list)
    output_checksum: str | None = None


# ---------------------------------------------------------------------------
# Provenance  (Evidence Framework §6)
# ---------------------------------------------------------------------------


class ProvenanceBase(BaseModel):
    """Common provenance fields mandated by Evidence Framework §6. Each
    service module (physicochemical.py, structural.py, ...) extends this
    with the `originating_modules` / model-version fields shown in that
    service's own Section 14 schematic."""

    model_config = ConfigDict(extra="forbid")

    originating_service: str
    upstream_evidence_ids: list[uuid.UUID] = Field(default_factory=list)
    algorithms: list[str] = Field(default_factory=list)
    model_checkpoints: list[str] = Field(default_factory=list)
    parameters: dict[str, Any] = Field(default_factory=dict)
    external_databases_used: list[str] = Field(default_factory=list)
    execution_timestamps: list[datetime] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Evidence Object envelope  (Evidence Framework §3-4)
# ---------------------------------------------------------------------------


class EvidenceHeader(BaseModel):
    model_config = ConfigDict(extra="forbid")

    evidence_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    evidence_type: str
    producing_service: str
    subject_id: uuid.UUID = Field(
        description="peptide_id, or a composite peptide+target pair identifier "
        "where the evidence is target-dependent (e.g. Structural, Functional)."
    )
    execution_id: uuid.UUID
    schema_version: str = Field(
        default="1.0.0",
        description="Semantic version of THIS evidence schema, per Evidence "
        "Framework §11 (MAJOR.MINOR.PATCH).",
    )
    timestamp: datetime = Field(default_factory=_utcnow)


class EvidenceObjectBase(BaseModel):
    """Common envelope every Evidence Object shares, per Evidence Framework §3:

        Header / Scientific Payload / Confidence / Uncertainty /
        Applicability Domain / Validation / Provenance / Metadata /
        Audit Information

    Concrete service Evidence Objects (see physicochemical.py, structural.py,
    functional.py, developability.py, safety.py) subclass this and add:
      - a strongly-typed scientific payload (the service-specific fields)
      - a service-specific `provenance` (subclassing ProvenanceBase)
      - a service-specific `confidence_summary` (this IS the "Confidence"
        slot from §3 -- see module docstring ASSUMPTION 2)

    Every subclass MUST set the class variables EVIDENCE_TYPE and
    PRODUCING_SERVICE, and use the `.new(...)` constructor to get a header
    that is guaranteed consistent with them.
    """

    model_config = ConfigDict(extra="forbid")

    EVIDENCE_TYPE: ClassVar[str]
    PRODUCING_SERVICE: ClassVar[str]

    header: EvidenceHeader
    uncertainty: UncertaintyBlock = Field(default_factory=UncertaintyBlock)
    applicability_domain: ApplicabilityDomain = Field(default_factory=ApplicabilityDomain)
    validation_status: ValidationStatus = ValidationStatus.NOT_VALIDATED
    known_limitations: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    metadata: MetadataBlock

    @field_validator("header")
    @classmethod
    def _header_matches_evidence_type(cls, v: EvidenceHeader) -> EvidenceHeader:
        if v.evidence_type != cls.EVIDENCE_TYPE:
            raise ValueError(
                f"{cls.__name__}: header.evidence_type must be "
                f"'{cls.EVIDENCE_TYPE}', got '{v.evidence_type}'"
            )
        return v

    @classmethod
    def new_header(
        cls, *, subject_id: uuid.UUID, execution_id: uuid.UUID, **kw: Any
    ) -> EvidenceHeader:
        """Convenience constructor for a header that is guaranteed consistent
        with this class's EVIDENCE_TYPE / PRODUCING_SERVICE."""
        return EvidenceHeader(
            evidence_type=cls.EVIDENCE_TYPE,
            producing_service=cls.PRODUCING_SERVICE,
            subject_id=subject_id,
            execution_id=execution_id,
            **kw,
        )
