"""
Physicochemical Evidence Object.

Source: 07_Physicochemical_Service_Specification.md, Section 14
("Evidence Generated by the Service").

The schematic tree in that section is reproduced field-for-field below,
using the shared primitives in common.py. Fields whose exact numeric type
was not specified in the source doc are given a reasonable concrete type
(e.g. float for scores) -- flagged inline where the choice is non-obvious.
"""

from __future__ import annotations

import uuid
from typing import ClassVar, Literal

from pydantic import BaseModel, ConfigDict, Field

from .common import (
    EvidenceObjectBase,
    FieldConfidence,
    ProvenanceBase,
    ValueConfidence,
)

# §5.1 / §12: the finite set of pipeline modules this service runs.
PhysicochemicalModule = Literal[
    "sequence_validation",
    "descriptor_calculator",
    "feature_generator",
    "evidence_generator",
]


class PhysicochemicalProvenance(ProvenanceBase):
    originating_modules: list[PhysicochemicalModule] = Field(default_factory=list)
    embedding_model_identifier_and_version: str | None = Field(
        default=None, description="e.g. 'ESM-2:esm2_t33_650M_UR50D-v2024.1'"
    )
    reference_parameter_sets: dict[str, str] = Field(
        default_factory=dict,
        description="e.g. {'hydrophobicity_scale': 'Kyte-Doolittle', "
        "'pKa_set': 'EMBOSS-iep', 'mass_table': 'IUPAC-2021'} -- per §6.",
    )


class NetChargeByPh(BaseModel):
    """§6.2 -- Henderson-Hasselbalch charge profile across a pH range."""

    model_config = ConfigDict(extra="forbid")

    profile: dict[str, float] = Field(
        description="pH (as string key, e.g. '7.4') -> net charge Q(p)."
    )
    confidence: FieldConfidence


class HydrophobicityProfile(BaseModel):
    """§6.3 -- GRAVY plus windowed hydrophobicity."""

    model_config = ConfigDict(extra="forbid")

    windowed_values: list[float]
    window_size: int = Field(ge=1, description="Typically 5-9 residues per §6.3.")
    confidence: FieldConfidence


class HydrophobicMoment(BaseModel):
    """§6.4 -- Eisenberg hydrophobic moment (mu_H)."""

    model_config = ConfigDict(extra="forbid")

    value: float | None
    assumed_periodicity_degrees: float = Field(
        description="100 for an assumed alpha-helix, 160-180 for a beta-strand, per §6.4."
    )
    confidence: FieldConfidence


class ChargeDistribution(BaseModel):
    """§6.5 -- positional variance of charge sign along the sequence."""

    model_config = ConfigDict(extra="forbid")

    profile: list[float]
    confidence: FieldConfidence


class InstabilityIndex(BaseModel):
    """§6.6 -- Guruprasad et al. instability index. II > 40 => 'unstable'."""

    model_config = ConfigDict(extra="forbid")

    value: float | None
    classification: Literal["stable", "unstable"] | None = None
    confidence: FieldConfidence


class CompositionalStatistics(BaseModel):
    model_config = ConfigDict(extra="forbid")

    aa_frequencies: dict[str, float]
    dipeptide_frequencies: dict[str, float]
    cys_count: int = Field(ge=0)
    pro_content: float = Field(ge=0.0, le=1.0)
    gly_content: float = Field(ge=0.0, le=1.0)
    confidence: FieldConfidence


class Descriptors(BaseModel):
    """The full set of deterministic descriptors from Section 6."""

    model_config = ConfigDict(extra="forbid")

    molecular_weight: ValueConfidence[float]  # §6.1
    isoelectric_point: ValueConfidence[float]  # §6.2
    net_charge_by_ph: NetChargeByPh  # §6.2
    gravy_score: ValueConfidence[float]  # §6.3
    hydrophobicity_profile: HydrophobicityProfile  # §6.3
    hydrophobic_moment: HydrophobicMoment  # §6.4
    charge_distribution: ChargeDistribution  # §6.5
    instability_index: InstabilityIndex  # §6.6
    aliphatic_index: ValueConfidence[float]  # §6.7
    aromaticity: ValueConfidence[float]  # §6.8
    boman_index: ValueConfidence[float]
    compositional_statistics: CompositionalStatistics


class EmbeddingVector(BaseModel):
    """Large scientific assets are referenced, not inlined -- see
    common.py ASSUMPTION 5 and Database Design Spec §6-7."""

    model_config = ConfigDict(extra="forbid")

    dimension: int = Field(ge=1)
    confidence: FieldConfidence
    storage_uri: str | None = Field(
        default=None,
        description="e.g. 's3://hakase/embeddings/{evidence_id}_pooled.npy'",
    )


class Embeddings(BaseModel):
    model_config = ConfigDict(extra="forbid")

    pooled_vector: EmbeddingVector
    per_residue_matrix: EmbeddingVector


class PhysicochemicalConfidenceSummary(BaseModel):
    """Per §14: deterministic vs. embedding-derived confidence are reported
    separately rather than blended, consistent with the platform-wide
    'per-component, not blended' confidence philosophy."""

    model_config = ConfigDict(extra="forbid")

    deterministic_tier: FieldConfidence
    embedding_tier: FieldConfidence
    aggregate_note: str | None = None


class PhysicochemicalEvidence(EvidenceObjectBase):
    """Physicochemical Evidence Object -- Physicochemical Service Spec §14."""

    EVIDENCE_TYPE: ClassVar[str] = "physicochemical"
    PRODUCING_SERVICE: ClassVar[str] = "physicochemical-service"

    peptide_object_reference: uuid.UUID
    descriptors: Descriptors
    embeddings: Embeddings
    provenance: PhysicochemicalProvenance
    confidence_summary: PhysicochemicalConfidenceSummary
