# Engine model id in the Model Registry (deterministic biochemistry engine).
_ENGINE_MODEL_ID = "peptide_biochem_engine"

# Lengths at which a couple of descriptors are documented as less reliable
# (spec §12: "very short or unusually long for a peptide"). Only the affected
# descriptors are down-graded to ``reduced`` — never the whole evidence object.
_SHORT_LEN = 5  # instability index & hydrophobic moment noisy below this
_LONG_LEN = 200  # unusually long for a peptide


def _fc(tier: str, rationale: str | None = None) -> dict[str, Any]:
    """Build a per-field confidence dict (schema: FieldConfidence)."""
    d: dict[str, Any] = {"tier": tier}
    if rationale:
        d["rationale"] = rationale
    return d


@dataclass(frozen=True)
class _EmbeddingBuild:
    """Everything the §14 embeddings block + its knock-on evidence fields need."""

    embeddings: dict[str, Any]  # payload embeddings block
    embedding_tier: str  # confidence_summary.embedding_tier
    validation_status: str  # payload-level: complete | partially_complete
    model_identifier: str | None  # provenance.embedding_model_identifier_and_version
    extrapolation_flag: bool  # feeds applicability_domain.extrapolation_flag
    summary_note: str  # appended to confidence_summary.aggregate_note
    limitation: str  # appended to evidence limitations
    warnings: list[str]


def _embeddings_unavailable(reason: str, *, warning: str | None = None) -> _EmbeddingBuild:
    """The sanctioned 'no embedding' result (spec §12): the object is still
    published with the embedding field explicitly ``unavailable`` — never a
    fabricated vector."""
    conf = _fc("unavailable", reason)
    return _EmbeddingBuild(
        embeddings={
            "pooled_vector": {"dimension": None, "storage_uri": None, "confidence": conf},
            "per_residue_matrix": {"dimension": None, "storage_uri": None, "confidence": conf},
        },
        embedding_tier="unavailable",
        validation_status="partially_complete",
        model_identifier=None,
        extrapolation_flag=False,
        summary_note=f"Embedding unavailable: {reason}",
        limitation=f"Sequence embedding (spec §6.11) unavailable: {reason}",
        warnings=[warning] if warning else [],
    )


def _build_embeddings(context: ExecutionContext) -> _EmbeddingBuild:
    """Generate, store-by-reference, and confidence-annotate the §6.11 embeddings.

    - The pooled vector and (for a real PLM) the per-residue matrix are written to
      the embedding store; only ``dimension`` + ``storage_uri`` land in the payload.
    - ``validation_status`` is ``complete`` only for a genuine learned PLM embedding
      that yields BOTH pooled + per-residue; the deterministic descriptor surrogate
      is ``partially_complete`` with ``embedding_tier = reduced`` and the per-residue
      matrix ``unavailable`` (roadmap "Decisions (locked)").
    - Any failure (no key, network, parse, storage) degrades gracefully to an
      explicit ``unavailable`` embedding — the evidence object is still published.
    """
    pep = context.peptide
    cfg = context.config
    try:
        provider = resolve_embedding_provider(cfg)
        result = provider.embed(pep.sequence)
        store = resolve_embedding_store(cfg)
        pooled_uri = store.put(
            subject_id=pep.subject_id,
            model_id=result.model_id,
            model_version=result.model_version,
            kind=POOLED,
            array=result.mean_vector,
        )
    except ServiceFailure as exc:
        return _embeddings_unavailable(
            str(exc),
            warning=f"embedding unavailable: {exc.reason_code}",
        )
    except Exception as exc:  # noqa: BLE001 — never fabricate; degrade gracefully
        return _embeddings_unavailable(
            f"embedding generation error: {exc}",
            warning="embedding unavailable: embedding_error",
        )

    model_identifier = f"{result.model_id}:{result.model_version}"
    applic = embedding_applicability(pep.sequence)
    is_plm = getattr(provider, "is_plm", False)
    has_matrix = result.per_residue is not None and len(result.per_residue) > 0

    # Completeness (locked): only a real PLM emitting BOTH vectors is "complete".
    if is_plm and has_matrix:
        embedding_tier = "exact" if applic.in_domain else "reduced"
        validation_status = "complete"
    else:
        embedding_tier = "reduced"
        validation_status = "partially_complete"

    if not is_plm:
        pooled_reason = (
            "Deterministic descriptor surrogate (reproducible, key-free); a real "
            "learned PLM embedding requires NVIDIA_API_KEY (ESM2)."
        )
        summary_note = (
            "Embedding is the deterministic descriptor surrogate (no PLM key "
            "configured): pooled vector present, per-residue matrix unavailable; "
            "treated as embedding_tier=reduced (spec §6.11)."
        )
        limitation = (
            "Sequence embedding (spec §6.11) is the deterministic descriptor "
            "surrogate; no learned per-residue representation without an ESM2 key."
        )
    elif applic.in_domain:
        pooled_reason = "Learned PLM embedding; input within the applicability domain."
        summary_note = "Learned PLM embedding generated (pooled + per-residue)."
        limitation = (
            "Sequence embedding (spec §6.11) is a learned PLM representation stored by reference."
        )
    else:
        pooled_reason = "Learned PLM embedding; out of domain — " + applic.note
        summary_note = "Learned PLM embedding generated but out of domain: " + applic.note
        limitation = (
            "Sequence embedding (spec §6.11) generated but flagged out of applicability domain."
        )

    pooled_vector = {
        "dimension": result.dim,
        "storage_uri": pooled_uri,
        "confidence": _fc(embedding_tier, pooled_reason),
    }
    if has_matrix:
        per_residue_uri = store.put(
            subject_id=pep.subject_id,
            model_id=result.model_id,
            model_version=result.model_version,
            kind=PER_RESIDUE,
            array=result.per_residue,
        )
        per_residue_matrix = {
            "dimension": len(result.per_residue[0]),
            "storage_uri": per_residue_uri,
            "confidence": _fc(embedding_tier, "Per-residue matrix stored by reference."),
        }
    else:
        per_residue_matrix = {
            "dimension": None,
            "storage_uri": None,
            "confidence": _fc(
                "unavailable",
                "Pooled-only representation; no per-residue matrix for this provider (spec §6.11).",
            ),
        }

    return _EmbeddingBuild(
        embeddings={"pooled_vector": pooled_vector, "per_residue_matrix": per_residue_matrix},
        embedding_tier=embedding_tier,
        validation_status=validation_status,
        model_identifier=model_identifier,
        extrapolation_flag=applic.extrapolation_flag,
        summary_note=summary_note,
        limitation=limitation,
        warnings=[],
    )


class PhysicochemicalService(ScientificService):
    name = "physicochemical_service"
    evidence_type = EvidenceType.PHYSICOCHEMICAL
    depends_on = []

    def run(self, context: ExecutionContext) -> EvidenceObject:
        pep = context.peptide
        props = properties_for(pep)

        phys = props.get("physicochemical", {})
        length = pep.length

        # ── Per-descriptor confidence tiers (§10.1) ───────────────────────────
        # All standard-residue closed-form descriptors are EXACT. A couple are
        # down-graded to REDUCED at extreme lengths (§12). The UNAVAILABLE path
        # exists for any descriptor whose engine value is missing (None) — the
        # sanctioned "could not compute" response, never a fabricated number.
        extreme_len = length < _SHORT_LEN or length > _LONG_LEN
        len_note = (
            f"Sequence length {length} outside the reliable range "
            f"[{_SHORT_LEN}, {_LONG_LEN}]; value retained but flagged (spec §12)."
        )

        def tier_for(value: Any, *, length_sensitive: bool = False) -> dict[str, Any]:
            if value is None:
                return _fc("unavailable", "No reference parameters for this input.")
            if length_sensitive and extreme_len:
                return _fc("reduced", len_note)
            return _fc("exact", "Closed-form computation over standard residues.")

        # ── Map engine output → typed §14 descriptors block ──────────────────
        charge_prof = props.get("charge_profile", {})
        net_charge_by_ph = {
            "4.0": charge_prof.get("pH_4_0"),
            "5.0": charge_prof.get("pH_5_0"),
            "6.0": charge_prof.get("pH_6_0"),
            "7.4": charge_prof.get("pH_7_4"),
            "8.0": charge_prof.get("pH_8_0"),
            "9.0": charge_prof.get("pH_9_0"),
        }
        net_charge_by_ph = {k: v for k, v in net_charge_by_ph.items() if v is not None}

        hp = props.get("hydrophobicity_profile", {})
        cd = props.get("charge_distribution", {})
        cs = props.get("compositional_statistics", {})

        instability_val = phys.get("instability_index")
        instability_class = (
            None if instability_val is None else ("unstable" if instability_val > 40 else "stable")
        )

        descriptors = {
            "molecular_weight": {
                "value": phys.get("molecular_weight_avg_da"),
                "confidence": tier_for(phys.get("molecular_weight_avg_da")),
            },
            "isoelectric_point": {
                "value": phys.get("isoelectric_point"),
                "confidence": tier_for(phys.get("isoelectric_point")),
            },
            "net_charge_by_ph": {
                "profile": net_charge_by_ph,
                "confidence": tier_for(net_charge_by_ph or None),
            },
            "gravy_score": {
                "value": phys.get("gravy"),
                "confidence": tier_for(phys.get("gravy")),
            },
            "hydrophobicity_profile": {
                "windowed_values": hp.get("windowed_values", []),
                "window_size": hp.get("window_size", 1),
                "scale": hp.get("scale", "Kyte-Doolittle"),
                "confidence": tier_for(hp.get("windowed_values")),
            },
            "hydrophobic_moment": {
                "value": phys.get("hydrophobic_moment"),
                "assumed_periodicity_degrees": phys.get(
                    "hydrophobic_moment_periodicity_deg", 100.0
                ),
                "beta_value": phys.get("hydrophobic_moment_beta"),
                "confidence": tier_for(phys.get("hydrophobic_moment"), length_sensitive=True),
            },
            "charge_distribution": {
                "profile": cd.get("profile", []),
                "variance": cd.get("variance", 0.0),
                "confidence": tier_for(cd.get("profile")),
            },
            "instability_index": {
                "value": instability_val,
                "classification": instability_class,
                "confidence": tier_for(instability_val, length_sensitive=True),
            },
            "aliphatic_index": {
                "value": phys.get("aliphatic_index"),
                "confidence": tier_for(phys.get("aliphatic_index")),
            },
            "aromaticity": {
                "value": phys.get("aromaticity"),
                "confidence": tier_for(phys.get("aromaticity")),
            },
            "boman_index": {
                "value": phys.get("boman_index"),
                "confidence": tier_for(phys.get("boman_index")),
            },
            "compositional_statistics": {
                "aa_frequencies": cs.get("aa_frequencies", {}),
                "dipeptide_frequencies": cs.get("dipeptide_frequencies", {}),
                "cys_count": cs.get("cys_count", 0),
                "pro_content": cs.get("pro_content", 0.0),
                "gly_content": cs.get("gly_content", 0.0),
                "confidence": tier_for(cs.get("aa_frequencies") or None),
            },
        }

        # ── Embeddings (§6.11) — generated, stored by reference, OOD-flagged ──
        # Real vectors written to the embedding store (pooled + per-residue) and
        # referenced by storage_uri; on any failure the block degrades to an
        # explicit `unavailable` and the evidence is still published (§12).
        emb = _build_embeddings(context)
        embeddings = emb.embeddings

        # ── Confidence summary (§10.3) — roll-up, never a replacement ─────────
        det_tiers = [d["confidence"]["tier"] for d in descriptors.values()]  # type: ignore[index]
        if any(t == "unavailable" for t in det_tiers):
            deterministic_tier = "reduced"
            agg = (
                "One or more descriptors unavailable for this input; see the "
                "per-descriptor breakdown. Remaining descriptors are exact."
            )
        elif any(t == "reduced" for t in det_tiers):
            deterministic_tier = "reduced"
            agg = (
                "Length-sensitive descriptors flagged reduced (spec §12); all "
                "other descriptors exact. See per-descriptor breakdown."
            )
        else:
            deterministic_tier = "exact"
            agg = "All deterministic descriptors computed exactly."
        # Deterministic and embedding confidence are reported separately (§10.3);
        # the roll-up never replaces the per-descriptor / per-vector breakdown.
        confidence_summary = {
            "deterministic_tier": deterministic_tier,
            "embedding_tier": emb.embedding_tier,
            "aggregate_note": f"{agg} {emb.summary_note}",
        }

        # ── Provenance (§14) — parameter-set + model versions ─────────────────
        engine_version = get_model_registry().version_map([_ENGINE_MODEL_ID]).get(_ENGINE_MODEL_ID)
        model_ident = f"{_ENGINE_MODEL_ID}:{engine_version}" if engine_version else _ENGINE_MODEL_ID
        reference_parameter_sets = props.get("reference_parameter_sets", {})
        typed_provenance = {
            "originating_modules": [
                "sequence_validation",
                "descriptor_calculator",
                "evidence_generator",
            ],
            "model_identifier_and_version": model_ident,
            "embedding_model_identifier_and_version": emb.model_identifier,
            "reference_parameter_sets": reference_parameter_sets,
        }

        # §14 completeness axis (distinct from the dataclass ValidationStatus enum):
        # "complete" only when a real learned PLM embedding produced both a pooled
        # vector and a per-residue matrix; the descriptor surrogate / any embedding
        # failure keeps it "partially_complete" (roadmap "Decisions (locked)").
        payload_validation_status = emb.validation_status

        # ── Validate the typed §14 payload block, then persist it ─────────────
        typed = PhysicochemicalTypedPayload.model_validate(
            {
                "peptide_object_reference": pep.subject_id,
                "descriptors": descriptors,
                "embeddings": embeddings,
                "provenance": typed_provenance,
                "confidence_summary": confidence_summary,
                "validation_status": payload_validation_status,
            }
        )

        payload: dict[str, Any] = {
            # Legacy/back-compat blocks — decision variables resolve against
            # ``physicochemical.*`` (see decision/variables.py). Do NOT rename.
            "physicochemical": phys,
            "secondary_structure": props.get("secondary_structure", {}),
            "charge_profile": charge_prof,
            "hbd_hba": props.get("hbd_hba", {}),
            "sequence": pep.sequence,
            "length": pep.length,
            "cyclic": pep.cyclic,
            "environment": {"ph": pep.ph, "ionic_strength_mM": pep.ionic_strength_mM},
        }
        # Merge the validated §14 block (peptide_object_reference, descriptors,
        # embeddings, provenance, confidence_summary, validation_status) at the
        # payload root. mode="json" keeps the payload plain (enums -> strings).
        payload.update(typed.model_dump(mode="json"))

        provenance = Provenance(
            originating_service=self.name,
            algorithms=[
                "Henderson-Hasselbalch net charge",
                "Kyte-Doolittle GRAVY + windowed hydrophobicity",
                "Guruprasad instability index",
                "Eisenberg hydrophobic moment (helix 100 deg / beta 160 deg)",
                "Positional charge-distribution variance",
                "Chou-Fasman/PSIPRED-style propensity",
            ],
            model_checkpoints=(
                [model_ident, emb.model_identifier] if emb.model_identifier else [model_ident]
            ),
            parameters={
                "ph": pep.ph,
                "ionic_strength_mM": pep.ionic_strength_mM,
                "cyclic": pep.cyclic,
                "reference_parameter_sets": reference_parameter_sets,
            },
            references=[
                "Kyte & Doolittle 1982 J Mol Biol 157:105",
                "Guruprasad 1990 Protein Eng 4:155",
                "Eisenberg 1984 J Mol Biol 179:125",
            ],
        )

        limitations = [
            "All descriptors derive from primary sequence and declared "
            "modifications only; no tertiary-structure context (spec §11).",
            "Hydrophobic moment assumes an idealized secondary-structure "
            "periodicity; it does not reflect the true 3D presentation (spec §11).",
            emb.limitation,
        ]
        if extreme_len:
            limitations.append(len_note)

        # Embedding out-of-domain (length / composition, §10.2) is a distinct
        # applicability signal from the deterministic extreme-length flag; either
        # one makes the input an extrapolation for downstream reasoning.
        embedding_ood = emb.extrapolation_flag
        extrapolation = extreme_len or embedding_ood

        return self._evidence(
            context,
            payload=payload,
            confidence=Confidence.make(
                1.0 if deterministic_tier == "exact" else 0.5,
                "deterministic_exact",
                rationale=(
                    "Closed-form biochemistry; exact for the standard 20 amino "
                    "acids. Per-descriptor tiers carried in the payload."
                ),
            ),
            uncertainty=Uncertainty(
                model_uncertainty=0.0,
                numerical_uncertainty=1e-6,
                sources=["floating_point_rounding"],
            ),
            applicability=ApplicabilityDomain(
                in_domain=not extrapolation,
                supported_length_range=[2, 1000],
                supported_residue_types="standard_20",
                modification_support="linear_cyclic_disulfide",
                modality_support="all",
                extrapolation_flag=extrapolation,
                notes=(
                    "Deterministic descriptors apply to any standard-residue peptide."
                    + (f" Embedding out of domain: {emb.summary_note}" if embedding_ood else "")
                ),
            ),
            provenance=provenance,
            tier=EvidenceTier.DETERMINISTIC,
            validation_status=ValidationStatus.INTERNALLY_VALIDATED,
            limitations=limitations,
            warnings=emb.warnings or None,
        )
