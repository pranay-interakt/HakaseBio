/**
 * The ADMET endpoint registry.
 *
 * This mirrors the backend registry that owns endpoint identity, units, unit
 * provenance, screening bands, model performance and the written interpretation
 * for every Layer-1 endpoint. In the platform these fields travel with each
 * prediction; here they are the same contract, held locally so the demo can
 * render an identical endpoint card.
 */

export type EndpointTask = "regression" | "binary_classification";

export type EndpointSpec = {
  /** Backend endpoint key, shown verbatim under the display title. */
  key: string;
  title: string;
  section: "Absorption" | "Distribution" | "Metabolism" | "Excretion" | "Toxicity" | "Physchem";
  task: EndpointTask;
  /** The unit the model natively predicts in. */
  nativeUnit: string;
  /** The unit the reference range is written in; blank when identical. */
  canonicalUnit?: string;
  /** Conversion applied to reach the canonical unit. */
  convert?: (value: number) => number;
  unitsSource: string;
  predicts: string;
  model: string;
  modelPerformance: string;
  modelSpeciesBasis: string;
  datasetSize: number;
  validationMetric: string;
  validationValue: number;
  validationScope: string;
  benchmarkReliability: "high" | "moderate" | "indicative";
  referenceUrl: string;
  /** Screening bands, expressed in the canonical unit. */
  bands?: { favourable: string; review: string; concern: string; context: string };
  /** Cut-points used to decide the band; direction says which side is good. */
  cuts?: [number, number];
  direction?: "lower_is_favourable" | "higher_is_favourable";
  /** Endpoints with no validated decision cutoff are reported, never graded. */
  ungradedReason?: string;
  scientistMeaning: string;
  developmentImplication: string;
  recommendedFollowUp: string;
  /** Plausible output range, used to project the demo's structure-derived value. */
  range: [number, number];
  notes?: string[];
};

