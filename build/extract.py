"""Extract site data from the repository's own generated documents and code.

Inputs (all inside hakase_operating_system):
  docs/18a_method_reference.md        generated from the method registry
  docs/validation/*.md                generated by hos.validation.cli
  docs/13_glossary.md                 the project glossary
  backend/hos/drivers                 the built-in study drivers
Nothing is typed in by hand here; re-run after the repository changes.
"""
import json, re, sys, pathlib
ROOT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent.parent
OUT = pathlib.Path(__file__).parent / "data"; OUT.mkdir(exist_ok=True)

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

# ---- methods ----
md = (ROOT / "docs/18a_method_reference.md").read_text()
areas, cur, meth, mode = [], None, None, None
for line in md.splitlines():
    if line.startswith("## "):
        name = line[3:].strip()
        if name == "Standing limitations":
            cur = None; continue
        cur = {"name": name, "slug": slug(name), "methods": []}; areas.append(cur); meth = None; continue
    if cur is None: continue
    if line.startswith("### "):
        meth = {"title": line[4:].strip(), "id": None, "version": None, "assumptions": [], "limits": [], "references": []}
        cur["methods"].append(meth); mode = None; continue
    if meth is None: continue
    m = re.match(r"^`([^`]+)` · version (\S+)", line)
    if m: meth["id"], meth["version"] = m.group(1), m.group(2); continue
    if line.strip() in ("Assumptions:", "Limits:", "References:"):
        mode = line.strip()[:-1].lower(); continue
    if line.startswith("- ") and mode:
        txt = line[2:].strip()
        if mode == "references":
            url = None
            mm = re.search(r"(https?://\S+)$", txt)
            if mm: url = mm.group(1); txt = txt[:mm.start()].strip()
            meth["references"].append({"text": txt, "url": url})
        else:
            meth[mode].append(txt)
standing = re.search(r"## Standing limitations\n\n(.*?)\n## ", md, re.S).group(1).strip()
json.dump({"areas": areas, "standing": standing}, open(OUT / "methods.json", "w"), indent=1)
print("methods", sum(len(a["methods"]) for a in areas), "areas", len(areas))

# ---- validation: end to end ----
e2e = (ROOT / "docs/validation/end_to_end_approved_drugs.md").read_text()
rows = []
for line in e2e.splitlines():
    if line.startswith("| ") and not line.startswith("| Drug") and not line.startswith("|---"):
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) == 6: rows.append(dict(zip(["drug", "measured", "estimated", "interval", "called", "truly"], cells)))
def grab(pat):
    m = re.search(pat, e2e); return m.group(1) if m else None
summary = {k: grab(p) for k, p in {
    "completed": r"Runs completed without error: \*\*(.+?)\*\*",
    "reconciles": r"Provenance ledger reconciles after the run: \*\*(.+?)\*\*",
    "no_prov": r"Values returned without provenance: \*\*(.+?)\*\*",
    "answered": r"Answered: \*\*(.+?)\*\*",
    "declined": r"declined: \*\*(.+?)\*\*",
    "median_fold": r"Median fold error: \*\*(.+?)\*\*",
    "within10": r"Median fold error: \*\*.+?\*\* \((.+?)\)",
    "bias": r"Signed bias: \*\*(.+?)\*\*",
    "interval": r"Stated interval contained the truth: \*\*(.+?)\*\*",
    "sensitivity": r"Sensitivity: \*\*(.+?)\*\* \((.+?)\)",
    "specificity": r"Specificity: \*\*(.+?)\*\* \((.+?)\)",
    "missed": r"Missed: (.+)",
    "overcalled": r"Over-called: (.+)",
}.items()}
summary["sensitivity_n"] = grab(r"Sensitivity: \*\*.+?\*\* \((.+?)\)")
summary["specificity_n"] = grab(r"Specificity: \*\*.+?\*\* \((.+?)\)")
intro = re.search(r"## End-to-end: approved drugs run as novel compounds\n\n(.+?)\n", e2e).group(1)
# ---- validation: model cards ----
mc = (ROOT / "docs/validation/herg_read_across.md").read_text()
cards = []
for block in re.split(r"\n## ", mc)[1:]:
    title = block.split("\n", 1)[0].strip()
    mid = re.search(r"`([^`]+)`", block); mid = mid.group(1) if mid else None
    risk = re.search(r"model risk\*\* — \*\*(\w+)\*\*", block)
    q = re.search(r"\*\*Question of interest\*\* — (.+)", block)
    role = re.search(r"\*\*Role in the decision\*\* — (.+)", block)
    oos = re.search(r"\*\*Out of scope\*\* — (.+)", block)
    gof = re.search(r"\*\*Goodness of fit, robustness, predictivity\*\* —\s*(.+?)\n5\.", block, re.S)
    gof = re.sub(r"\s+", " ", gof.group(1)).strip() if gof else None
    cards.append({"title": title, "id": mid, "risk": risk.group(1) if risk else None,
                  "question": q.group(1).strip() if q else None, "role": role.group(1).strip() if role else None,
                  "out_of_scope": oos.group(1).strip() if oos else None, "validation": gof,
                  "validated": bool(gof and "not yet externally validated" not in gof)})
json.dump({"e2e": {"intro": intro, "summary": summary, "rows": rows}, "cards": cards}, open(OUT / "validation.json", "w"), indent=1)
print("e2e rows", len(rows), "cards", len(cards), [c["id"] for c in cards if c["validated"]])

# ---- glossary ----
gl = (ROOT / "docs/13_glossary.md").read_text()
terms = []
for m in re.finditer(r"\*\*(.+?)\*\* — (.+?)(?=\n\n|\Z)", gl, re.S):
    terms.append({"term": m.group(1).strip(), "definition": re.sub(r"\s+", " ", m.group(2)).strip()})
json.dump(terms, open(OUT / "glossary_src.json", "w"), indent=1)
print("glossary", len(terms))

# ---- drivers ----
sys.path.insert(0, str(ROOT / "backend"))
from hos.drivers.registry import default_registry
drivers = []
for d in default_registry():
    drivers.append({"name": d.name, "version": getattr(d, "version", None), "description": getattr(d, "description", None)})
json.dump(drivers, open(OUT / "drivers.json", "w"), indent=1)
print("drivers", len(drivers))
